import { useState } from 'react';
import { ImageOff } from 'lucide-react';

interface ResilientImageProps {
  src: string;
  alt: string;
  className?: string;
  fallbackTitle?: string;
}

export function ResilientImage({
  src,
  alt,
  className = '',
  fallbackTitle = 'Boresha Elimu Initiative CBO · Malindi',
}: ResilientImageProps) {
  const [hasError, setHasError] = useState(false);

  if (hasError) {
    return (
      <div
        role="img"
        aria-label={alt}
        className={`flex flex-col items-center justify-center bg-surface text-ink-muted border border-rule p-6 text-center ${className}`}
      >
        <ImageOff className="w-7 h-7 mb-2 text-accent" aria-hidden="true" />
        <p className="text-sm font-medium text-ink">{fallbackTitle}</p>
        <p className="text-xs text-ink-subtle mt-1 max-w-xs">{alt}</p>
      </div>
    );
  }

  return (
    <img
      src={src}
      alt={alt}
      referrerPolicy="no-referrer"
      onError={() => setHasError(true)}
      className={className}
    />
  );
}
